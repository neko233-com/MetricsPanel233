func TestTeamCRUDSearchIsolationAndRestart(t *testing.T) {
	ctx := context.Background()
	location := filepath.Join(t.TempDir(), "identity.db")
	store, err := Open(location)
	require.NoError(t, err)
	defer func() { require.NoError(t, store.Close()) }()
	org, err := store.BeginOrganization(ctx, "Second organization")
	require.NoError(t, err)
	org, err = store.ActivateOrganization(ctx, org.ID, org.Version)
	require.NoError(t, err)
	team, err := store.CreateTeam(ctx, 1, TeamInput{Name: " Operations ", Email: " ops@example.test "})
	require.NoError(t, err)
	require.Equal(t, "Operations", team.Name)
	require.Equal(t, "ops@example.test", team.Email)
	require.Equal(t, TeamActive, team.State)
	require.NotEmpty(t, team.UID)
	require.EqualValues(t, 1, team.Version)
	require.Zero(t, team.MemberCount)
	other, err := store.CreateTeam(ctx, org.ID, TeamInput{Name: "Operations"})
	require.NoError(t, err)
	require.NotEqual(t, team.ID, other.ID)
	require.NotEqual(t, team.UID, other.UID)
	_, err = store.CreateTeam(ctx, 1, TeamInput{Name: "OPERATIONS"})
	require.ErrorIs(t, err, ErrTeamExists)
	_, err = store.Team(ctx, org.ID, team.ID)
	require.ErrorIs(t, err, sql.ErrNoRows)
	_, err = store.TeamByUID(ctx, org.ID, team.UID)
	require.ErrorIs(t, err, sql.ErrNoRows)
	_, err = store.UpdateTeam(ctx, org.ID, team.ID, team.Version, TeamUpdate{Name: serviceValue("Wrong organization")})
	require.ErrorIs(t, err, sql.ErrNoRows)
	_, err = store.DeleteTeam(ctx, org.ID, team.ID, team.Version)
	require.ErrorIs(t, err, sql.ErrNoRows)
	_, err = store.UpdateTeam(ctx, 1, team.ID, 0, TeamUpdate{Name: serviceValue("No version")})
	require.ErrorIs(t, err, ErrVersionConflict)
	updated, err := store.UpdateTeam(ctx, 1, team.ID, team.Version, TeamUpdate{Name: serviceValue("Platform"), Email: serviceValue("")})
	require.NoError(t, err)
	require.Equal(t, team.UID, updated.UID)
	require.Equal(t, team.CreatedAt, updated.CreatedAt)
	require.Greater(t, updated.UpdatedAt, team.UpdatedAt)
	require.EqualValues(t, team.Version+1, updated.Version)
	require.Empty(t, updated.Email)
	_, err = store.UpdateTeam(ctx, 1, team.ID, team.Version, TeamUpdate{Email: serviceValue("stale@example.test")})
	require.ErrorIs(t, err, ErrVersionConflict)
	_, err = store.DeleteTeam(ctx, 1, team.ID, team.Version)
	require.ErrorIs(t, err, ErrVersionConflict)
	for _, name := range []string{"Alpha", "Zebra", "Literal%_team"} {
		_, err := store.CreateTeam(ctx, 1, TeamInput{Name: name})
		require.NoError(t, err)
	}
	page, err := store.SearchTeams(ctx, 1, TeamSearch{Page: 2, PerPage: 2})
	require.NoError(t, err)
	require.EqualValues(t, 4, page.TotalCount)
	require.Equal(t, []string{"Platform", "Zebra"}, []string{page.Teams[0].Name, page.Teams[1].Name})
	page, err = store.SearchTeams(ctx, 1, TeamSearch{Query: "%_"})
	require.NoError(t, err)
	require.EqualValues(t, 1, page.TotalCount)
	require.Equal(t, "Literal%_team", page.Teams[0].Name)
	page, err = store.SearchTeams(ctx, org.ID, TeamSearch{Name: "OPERATIONS", ID: other.ID})
	require.NoError(t, err)
	require.Equal(t, []Team{other}, page.Teams)
	require.Equal(t, 1, page.Page)
	require.Equal(t, 1000, page.PerPage)
	for _, input := range []TeamInput{{}, {Name: "bad\nname"}, {Name: string([]byte{0xff})}, {Name: strings.Repeat("x", 257)}, {Name: "Bad email", Email: "Name <valid@example.test>"}, {Name: "Bad email", Email: "not-email"}} {
		_, err := store.CreateTeam(ctx, 1, input)
		require.Error(t, err)
	}
	for _, query := range []TeamSearch{{Page: -1}, {PerPage: 1001}, {Page: math.MaxInt, PerPage: 1000}, {ID: -1}, {Query: "bad\nquery"}, {Name: string([]byte{0xff})}} {
		_, err := store.SearchTeams(ctx, 1, query)
		require.Error(t, err)
	}
	require.NoError(t, store.Close())
	store, err = Open(location)
	require.NoError(t, err)
	restored, err := store.TeamByUID(ctx, 1, updated.UID)
	require.NoError(t, err)
	require.Equal(t, updated, restored)
	var version int
	require.NoError(t, store.db.QueryRow(`SELECT version FROM identity_schema WHERE id=1`).Scan(&version))
	require.Equal(t, 6, version)
}

func TestTeamTypedMembersOrgBindingsAndForeignKeys(t *testing.T) {
	ctx := context.Background()
	store, org := openServiceAccountTestStore(t)
	user := teamTestUser(t, store, 1, "alice")
	foreignUser := teamTestUser(t, store, org.ID, "foreign")
	account, err := store.CreateServiceAccount(ctx, 1, ServiceAccountInput{Name: "Agent"})
	require.NoError(t, err)
	require.Equal(t, user.ID, account.ID, "the independent sequences deliberately collide")
	foreignAccount, err := store.CreateServiceAccount(ctx, org.ID, ServiceAccountInput{Name: "Foreign agent"})
	require.NoError(t, err)
	team, err := store.CreateTeam(ctx, 1, TeamInput{Name: "Operations"})
	require.NoError(t, err)
	foreignTeam, err := store.CreateTeam(ctx, org.ID, TeamInput{Name: "Operations"})
	require.NoError(t, err)
	human := TeamPrincipal{Kind: TypeUser, ID: user.ID}
	service := TeamPrincipal{Kind: TypeServiceAccount, ID: account.ID}
	member, err := store.AddTeamMember(ctx, 1, team.ID, team.Version, human, TeamMemberRole)
	require.NoError(t, err)
	require.Equal(t, user.Login, member.Login)
	require.Equal(t, human, member.Principal)
	team = teamTestRefresh(t, store, team)
	saMember, err := store.AddTeamMember(ctx, 1, team.ID, team.Version, service, TeamAdminRole)
	require.NoError(t, err)
	require.Equal(t, account.Login, saMember.Login)
	require.Equal(t, service, saMember.Principal)
	require.Empty(t, saMember.Email)
	team = teamTestRefresh(t, store, team)
	require.EqualValues(t, 2, team.MemberCount)
	for _, principal := range []TeamPrincipal{{Kind: TypeSystem, ID: user.ID}, {ID: user.ID}, {Kind: TypeUser}, {Kind: TypeUser, ID: foreignUser.ID}, {Kind: TypeServiceAccount, ID: foreignAccount.ID}, {Kind: TypeUser, ID: 999}} {
		_, err := store.AddTeamMember(ctx, 1, team.ID, team.Version, principal, TeamMemberRole)
		require.Error(t, err)
	}
	_, err = store.AddTeamMember(ctx, 1, team.ID, team.Version, human, TeamMemberRole)
	require.ErrorIs(t, err, ErrTeamMemberExists)
	_, err = store.AddTeamMember(ctx, 1, team.ID, team.Version, human, TeamRole(1))
	require.Error(t, err)
	_, err = store.AddTeamMember(ctx, org.ID, team.ID, team.Version, human, TeamAdminRole)
	require.ErrorIs(t, err, sql.ErrNoRows)
	_, err = store.TeamMembers(ctx, org.ID, team.ID)
	require.ErrorIs(t, err, sql.ErrNoRows)
	_, err = store.TeamMember(ctx, org.ID, team.ID, service)
	require.ErrorIs(t, err, sql.ErrNoRows)
	_, err = store.UpdateTeamMember(ctx, org.ID, team.ID, saMember.Version, service, TeamMemberRole)
	require.ErrorIs(t, err, sql.ErrNoRows)
	require.ErrorIs(t, store.RemoveTeamMember(ctx, org.ID, team.ID, member.Version, human), sql.ErrNoRows)

	// Both the API and SQLite enforce exactly one typed identity and its org.
	for _, args := range [][]any{
		{1, team.ID, "user", user.ID, account.ID, 0},
		{1, team.ID, "user", nil, account.ID, 0},
		{1, team.ID, "service-account", user.ID, nil, 0},
		{1, team.ID, "user", foreignUser.ID, nil, 0},
		{1, team.ID, "service-account", nil, foreignAccount.ID, 0},
		{1, foreignTeam.ID, "user", user.ID, nil, 0},
		{1, team.ID, "user", user.ID, nil, 1},
	} {
		_, err := store.db.Exec(`INSERT INTO team_members(org_id,team_id,principal_type,user_id,account_id,role,version,created_at,updated_at) VALUES(?,?,?,?,?,?,1,1,1)`, args...)
		require.Error(t, err)
	}
	members, err := store.TeamMembers(ctx, 1, team.ID)
	require.NoError(t, err)
	require.Len(t, members, 2)
	updated, err := store.UpdateTeamMember(ctx, 1, team.ID, member.Version, human, TeamAdminRole)
	require.NoError(t, err)
	require.Greater(t, updated.Version, member.Version)
	require.Equal(t, TeamAdminRole, updated.Role)
	principal, err := store.UserPrincipal(ctx, user.ID, 1)
	require.NoError(t, err)
	require.Equal(t, RoleViewer, principal.Role)
	require.False(t, principal.IsServerAdmin)
	_, err = store.UpdateTeamMember(ctx, 1, team.ID, member.Version, human, TeamMemberRole)
	require.ErrorIs(t, err, ErrVersionConflict)
	require.ErrorIs(t, store.RemoveTeamMember(ctx, 1, team.ID, member.Version, human), ErrVersionConflict)
	require.NoError(t, store.RemoveTeamMember(ctx, 1, team.ID, updated.Version, human))
	teamTestNoGrant(t, store, 1, human)
	remaining, err := store.TeamMember(ctx, 1, team.ID, service)
	require.NoError(t, err)
	require.Equal(t, saMember, remaining, "removing human ID 1 must not remove service-account ID 1")
	grants, err := store.TeamsForPrincipal(ctx, 1, service)
	require.NoError(t, err)
	require.Len(t, grants, 1)
	require.Equal(t, TeamAdminRole, grants[0].Role)
	teamTestNoGrant(t, store, org.ID, service)
	var foreignKeys int
	require.NoError(t, store.db.QueryRow(`PRAGMA foreign_keys`).Scan(&foreignKeys))
	require.Equal(t, 1, foreignKeys)
	rows, err := store.db.Query(`PRAGMA foreign_key_check`)
	require.NoError(t, err)
	require.False(t, rows.Next())
	require.NoError(t, rows.Err())
	require.NoError(t, rows.Close())
}

