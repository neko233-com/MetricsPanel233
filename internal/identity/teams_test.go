func TestTeamRemovalResumesAfterRestartAndNewIdentityHasNoOldACL(t *testing.T) {
	ctx := context.Background()
	directory := t.TempDir()
	location := filepath.Join(directory, "identity.db")
	store, err := Open(location)
	require.NoError(t, err)
	defer func() { require.NoError(t, store.Close()) }()
	user := teamTestUser(t, store, 1, "viewer")
	principal := TeamPrincipal{Kind: TypeUser, ID: user.ID}
	team, err := store.CreateTeam(ctx, 1, TeamInput{Name: "Operations"})
	require.NoError(t, err)
	_, err = store.AddTeamMember(ctx, 1, team.ID, team.Version, principal, TeamAdminRole)
	require.NoError(t, err)
	team = teamTestRefresh(t, store, team)
	// A separate resource database proves there is no fictitious cross-DB commit.
	resources, err := sql.Open("sqlite", filepath.Join(directory, "organization.db"))
	require.NoError(t, err)
	defer resources.Close()
	_, err = resources.Exec(`CREATE TABLE team_acl(org_id INTEGER,team_id INTEGER,team_uid TEXT); INSERT INTO team_acl VALUES(?,?,?)`, team.OrgID, team.ID, team.UID)
	require.NoError(t, err)
	_, err = store.DeleteTeam(ctx, 1, team.ID, team.Version-1)
	require.ErrorIs(t, err, ErrVersionConflict)
	pending, err := store.PendingTeamRemovals(ctx, 1, 0)
	require.NoError(t, err)
	require.Empty(t, pending)
	removal, err := store.DeleteTeam(ctx, 1, team.ID, team.Version)
	require.NoError(t, err)
	require.EqualValues(t, team.Version+1, removal.TargetVersion)
	require.Equal(t, team.UID, removal.TeamUID)
	teamTestNoGrant(t, store, 1, principal)
	_, err = store.Team(ctx, 1, team.ID)
	require.ErrorIs(t, err, sql.ErrNoRows)
	_, err = store.TeamMembers(ctx, 1, team.ID)
	require.ErrorIs(t, err, ErrTeamCleanup)
	_, err = store.UpdateTeam(ctx, 1, team.ID, removal.TargetVersion, TeamUpdate{Name: serviceValue("Revive")})
	require.ErrorIs(t, err, ErrTeamCleanup)
	_, err = store.AddTeamMember(ctx, 1, team.ID, removal.TargetVersion, principal, TeamMemberRole)
	require.ErrorIs(t, err, ErrTeamCleanup)
	_, err = store.CreateTeam(ctx, 1, TeamInput{Name: "OPERATIONS"})
	require.ErrorIs(t, err, ErrTeamExists)
	page, err := store.SearchTeams(ctx, 1, TeamSearch{})
	require.NoError(t, err)
	require.Empty(t, page.Teams)
	require.ErrorIs(t, store.CompleteTeamRemoval(ctx, 1, team.ID, 0), ErrVersionConflict)
	require.ErrorIs(t, store.CompleteTeamRemoval(ctx, 1, team.ID, removal.Version+1), ErrVersionConflict)
	require.ErrorIs(t, store.CompleteTeamRemoval(ctx, 2, team.ID, removal.Version), sql.ErrNoRows)
	var resourceCount int
	require.NoError(t, resources.QueryRow(`SELECT count(*) FROM team_acl`).Scan(&resourceCount))
	require.Equal(t, 1, resourceCount, "catalog deletion cannot pretend to clean another database")
	require.NoError(t, store.Close())
	store, err = Open(location)
	require.NoError(t, err)
	pending, err = store.PendingTeamRemovals(ctx, 1, 100)
	require.NoError(t, err)
	require.Equal(t, []TeamRemoval{removal}, pending)
	teamTestNoGrant(t, store, 1, principal)
	_, err = resources.Exec(`DELETE FROM team_acl WHERE org_id=? AND team_id=? AND team_uid=?`, removal.OrgID, removal.TeamID, removal.TeamUID)
	require.NoError(t, err)
	require.NoError(t, store.CompleteTeamRemoval(ctx, 1, team.ID, removal.Version))
	require.NoError(t, store.CompleteTeamRemoval(ctx, 1, team.ID, removal.Version), "same completed cleanup job is safely retryable")
	pending, err = store.PendingTeamRemovals(ctx, 1, 100)
	require.NoError(t, err)
	require.Empty(t, pending)
	deleted, err := loadTeam(ctx, store.db, 1, team.ID)
	require.NoError(t, err)
	require.Equal(t, TeamDeleted, deleted.State)
	require.Equal(t, team.UID, deleted.UID)
	require.EqualValues(t, removal.TargetVersion+1, deleted.Version)
	require.Zero(t, deleted.MemberCount)
	recreated, err := store.CreateTeam(ctx, 1, TeamInput{Name: "Operations"})
	require.NoError(t, err)
	require.NotEqual(t, team.ID, recreated.ID)
	require.NotEqual(t, team.UID, recreated.UID)
	require.Zero(t, recreated.MemberCount)
	teamTestNoGrant(t, store, 1, principal)
	require.NoError(t, resources.QueryRow(`SELECT count(*) FROM team_acl WHERE team_id=? OR team_uid=?`, recreated.ID, recreated.UID).Scan(&resourceCount))
	require.Zero(t, resourceCount)
	require.NoError(t, store.Close())
	store, err = Open(location)
	require.NoError(t, err)
	restored, err := store.Team(ctx, 1, recreated.ID)
	require.NoError(t, err)
	require.Equal(t, recreated, restored)
	require.NoError(t, store.CompleteTeamRemoval(ctx, 1, team.ID, removal.Version))
	require.Equal(t, recreated, teamTestRefresh(t, store, recreated))
}

func TestTeamCASConcurrentMembersAndABA(t *testing.T) {
	ctx := context.Background()
	store, _ := openServiceAccountTestStore(t)
	user := teamTestUser(t, store, 1, "viewer")
	principal := TeamPrincipal{Kind: TypeUser, ID: user.ID}
	team, err := store.CreateTeam(ctx, 1, TeamInput{Name: "Operations"})
	require.NoError(t, err)
	const writers = 8
	run := func(write func() error, missingAllowed bool) {
		var wg sync.WaitGroup
		results := make(chan error, writers)
		for range writers {
			wg.Add(1)
			go func() { defer wg.Done(); results <- write() }()
		}
		wg.Wait()
		close(results)
		winners := 0
		for err := range results {
			if err == nil {
				winners++
			} else if missingAllowed && errors.Is(err, sql.ErrNoRows) {
				continue
			} else {
				require.ErrorIs(t, err, ErrVersionConflict)
			}
		}
		require.Equal(t, 1, winners)
	}
	run(func() error {
		_, err := store.UpdateTeam(ctx, 1, team.ID, team.Version, TeamUpdate{Email: serviceValue("updated@example.test")})
		return err
	}, false)
	team = teamTestRefresh(t, store, team)
	run(func() error {
		_, err := store.AddTeamMember(ctx, 1, team.ID, team.Version, principal, TeamMemberRole)
		return err
	}, false)
	member, err := store.TeamMember(ctx, 1, team.ID, principal)
	require.NoError(t, err)
	run(func() error {
		_, err := store.UpdateTeamMember(ctx, 1, team.ID, member.Version, principal, TeamAdminRole)
		return err
	}, false)
	member, err = store.TeamMember(ctx, 1, team.ID, principal)
	require.NoError(t, err)
	run(func() error { return store.RemoveTeamMember(ctx, 1, team.ID, member.Version, principal) }, true)
	teamTestNoGrant(t, store, 1, principal)
	team = teamTestRefresh(t, store, team)
	newMember, err := store.AddTeamMember(ctx, 1, team.ID, team.Version, principal, TeamMemberRole)
	require.NoError(t, err)
	require.Greater(t, newMember.Version, member.Version)
	require.ErrorIs(t, store.RemoveTeamMember(ctx, 1, team.ID, member.Version, principal), ErrVersionConflict)
	_, err = store.UpdateTeamMember(ctx, 1, team.ID, member.Version, principal, TeamAdminRole)
	require.ErrorIs(t, err, ErrVersionConflict)
	current, err := store.TeamMember(ctx, 1, team.ID, principal)
	require.NoError(t, err)
	require.Equal(t, newMember, current)
}

func TestTeamRemovalFailureRollsBackMarkerAndMembers(t *testing.T) {
	ctx := context.Background()
	store, _ := openServiceAccountTestStore(t)
	account, err := store.CreateServiceAccount(ctx, 1, ServiceAccountInput{Name: "Agent"})
	require.NoError(t, err)
	team, err := store.CreateTeam(ctx, 1, TeamInput{Name: "Operations"})
	require.NoError(t, err)
	principal := TeamPrincipal{Kind: TypeServiceAccount, ID: account.ID}
	_, err = store.AddTeamMember(ctx, 1, team.ID, team.Version, principal, TeamMemberRole)
	require.NoError(t, err)
	team = teamTestRefresh(t, store, team)
	_, err = store.db.Exec(`CREATE TRIGGER reject_cleanup BEFORE INSERT ON team_removal_cleanup BEGIN SELECT RAISE(ABORT,'injected cleanup failure'); END`)
	require.NoError(t, err)
	_, err = store.DeleteTeam(ctx, 1, team.ID, team.Version)
	require.Error(t, err)
	require.Equal(t, team, teamTestRefresh(t, store, team))
	pending, err := store.PendingTeamRemovals(ctx, 1, 0)
	require.NoError(t, err)
	require.Empty(t, pending)
	_, err = store.db.Exec(`DROP TRIGGER reject_cleanup`)
	require.NoError(t, err)
	removal, err := store.DeleteTeam(ctx, 1, team.ID, team.Version)
	require.NoError(t, err)
	_, err = store.db.Exec(`CREATE TRIGGER reject_completion BEFORE UPDATE OF state ON teams WHEN NEW.state='deleted' BEGIN SELECT RAISE(ABORT,'injected finalization failure'); END`)
	require.NoError(t, err)
	require.Error(t, store.CompleteTeamRemoval(ctx, 1, team.ID, removal.Version))
	deleting, err := loadTeam(ctx, store.db, 1, team.ID)
	require.NoError(t, err)
	require.Equal(t, TeamDeleting, deleting.State)
	require.EqualValues(t, 1, deleting.MemberCount, "purging members rolled back with failed finalization")
	pending, err = store.PendingTeamRemovals(ctx, 1, 0)
	require.NoError(t, err)
	require.Equal(t, []TeamRemoval{removal}, pending)
	_, err = store.db.Exec(`DROP TRIGGER reject_completion`)
	require.NoError(t, err)
	require.NoError(t, store.CompleteTeamRemoval(ctx, 1, team.ID, removal.Version))
	teamTestNoGrant(t, store, 1, principal)
}
