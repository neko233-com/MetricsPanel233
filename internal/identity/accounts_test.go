func TestPasswordsSessionsAndMembershipRevocationSurviveRestart(t *testing.T) {
	ctx := context.Background()
	path := filepath.Join(t.TempDir(), "identity.db")
	catalog, err := Open(path)
	require.NoError(t, err)
	t.Cleanup(func() { catalog.Close() })
	admin, err := catalog.BootstrapAdmin(ctx, UserInput{Login: "admin", Name: "Administrator", Password: "admin-password-233"})
	require.NoError(t, err)
	require.True(t, admin.IsServerAdmin)
	_, err = catalog.BootstrapAdmin(ctx, UserInput{Login: "another-admin", Password: "another-admin-password"})
	require.ErrorIs(t, err, ErrAlreadyBootstrapped)
	user, err := catalog.CreateUser(ctx, UserInput{Login: "reader", Email: "reader@example.com", Password: "reader-password-233", OrgID: 1, Role: RoleViewer})
	require.NoError(t, err)
	p, err := catalog.AuthenticatePassword(ctx, "READER@example.com", "reader-password-233", 0)
	require.NoError(t, err)
	require.Equal(t, user.ID, p.ID)
	require.Equal(t, RoleViewer, p.Role)
	_, err = catalog.AuthenticatePassword(ctx, "reader", "wrong-password-233", 0)
	require.ErrorIs(t, err, ErrUnauthenticated)
	_, err = catalog.AuthenticatePassword(ctx, "missing", "reader-password-233", 0)
	require.ErrorIs(t, err, ErrUnauthenticated)
	org, err := catalog.BeginOrganization(ctx, "Business")
	require.NoError(t, err)
	org, err = catalog.ActivateOrganization(ctx, org.ID, org.Version)
	require.NoError(t, err)
	_, err = catalog.AuthenticatePassword(ctx, "reader", "reader-password-233", org.ID)
	require.ErrorIs(t, err, ErrUnauthenticated)
	membership, err := catalog.AddOrganizationUser(ctx, org.ID, user.ID, RoleEditor)
	require.NoError(t, err)
	p, session, key, err := catalog.Login(ctx, "READER", "reader-password-233", 1, time.Hour, 30*time.Minute)
	require.NoError(t, err)
	require.EqualValues(t, 1, p.OrgID)
	require.NotEmpty(t, key)
	p, err = catalog.AuthenticateSession(ctx, key, org.ID)
	require.NoError(t, err)
	require.Equal(t, RoleEditor, p.Role)
	_, err = catalog.AuthenticateSession(ctx, key, 900)
	require.ErrorIs(t, err, ErrUnauthenticated)
	// Hashes and salt are private store fields, never part of account or session
	// DTOs; no raw credential is saved even while its browser session is active.
	var storedDigest []byte
	require.NoError(t, catalog.db.QueryRow(`SELECT token_hash FROM browser_sessions WHERE id=?`, session.ID).Scan(&storedDigest))
	expected, err := credentialDigest(key, sessionCredentialPrefix)
	require.NoError(t, err)
	require.Equal(t, expected, storedDigest)
	var salt, hash []byte
	var format string
	require.NoError(t, catalog.db.QueryRow(`SELECT salt,hash,format FROM password_credentials WHERE user_id=?`, user.ID).Scan(&salt, &hash, &format))
	require.Len(t, salt, 16)
	require.Len(t, hash, 32)
	require.Equal(t, passwordFormat, format)
	serialized, err := json.Marshal([]any{user, session})
	require.NoError(t, err)
	require.NotContains(t, string(serialized), key)
	require.NotContains(t, string(serialized), "reader-password-233")
	require.NotContains(t, string(serialized), "token_hash")
	require.NoError(t, catalog.Close())
	catalog, err = Open(path)
	require.NoError(t, err)
	p, err = catalog.AuthenticateSession(ctx, key, 0)
	require.NoError(t, err)
	require.EqualValues(t, 1, p.OrgID)
	p, err = catalog.SwitchSessionOrganization(ctx, key, org.ID)
	require.NoError(t, err)
	require.Equal(t, org.ID, p.OrgID)
	p, err = catalog.AuthenticatePassword(ctx, "reader", "reader-password-233", 0)
	require.NoError(t, err)
	require.Equal(t, org.ID, p.OrgID)
	membership, err = catalog.ChangeOrganizationUserRole(ctx, org.ID, user.ID, membership.Version, RoleViewer)
	require.NoError(t, err)
	p, err = catalog.AuthenticateSession(ctx, key, 0)
	require.NoError(t, err)
	require.Equal(t, RoleViewer, p.Role, "a session must recheck the current role")
	removing, err := catalog.RemoveOrganizationUser(ctx, org.ID, user.ID, membership.Version)
	require.NoError(t, err)
	_, err = catalog.AuthenticateSession(ctx, key, 1)
	require.ErrorIs(t, err, ErrUnauthenticated)
	_, err = catalog.AddOrganizationUser(ctx, org.ID, user.ID, RoleEditor)
	require.ErrorIs(t, err, ErrMembershipCleanup)
	require.ErrorIs(t, catalog.CompleteMembershipRemoval(ctx, org.ID, user.ID, removing.Version-1), ErrVersionConflict)
	require.NoError(t, catalog.CompleteMembershipRemoval(ctx, org.ID, user.ID, removing.Version))
	_, err = catalog.AddOrganizationUser(ctx, org.ID, user.ID, RoleEditor)
	require.NoError(t, err)
	_, err = catalog.AuthenticateSession(ctx, key, org.ID)
	require.ErrorIs(t, err, ErrUnauthenticated, "rejoining cannot revive a revoked cookie")
	_, _, newKey, err := catalog.Login(ctx, "reader", "reader-password-233", 1, time.Hour, time.Hour)
	require.NoError(t, err)
	current, err := catalog.User(ctx, user.ID)
	require.NoError(t, err)
	current, err = catalog.ChangePassword(ctx, user.ID, current.Version, "new-reader-password-233")
	require.NoError(t, err)
	_, err = catalog.AuthenticateSession(ctx, newKey, 0)
	require.ErrorIs(t, err, ErrUnauthenticated)
	_, err = catalog.AuthenticatePassword(ctx, "reader", "reader-password-233", 1)
	require.ErrorIs(t, err, ErrUnauthenticated)
	_, _, newKey, err = catalog.Login(ctx, "reader", "new-reader-password-233", 1, time.Hour, time.Hour)
	require.NoError(t, err)
	current, err = catalog.SetUserDisabled(ctx, user.ID, current.Version, true)
	require.NoError(t, err)
	_, err = catalog.AuthenticatePassword(ctx, "reader", "new-reader-password-233", 1)
	require.ErrorIs(t, err, ErrUnauthenticated)
	_, err = catalog.AuthenticateSession(ctx, newKey, 0)
	require.ErrorIs(t, err, ErrUnauthenticated)
	_, err = catalog.SetUserDisabled(ctx, user.ID, current.Version, false)
	require.NoError(t, err)
	_, err = catalog.AuthenticatePassword(ctx, "reader", "new-reader-password-233", 1)
	require.NoError(t, err)
	_, err = catalog.AuthenticateSession(ctx, newKey, 0)
	require.ErrorIs(t, err, ErrUnauthenticated, "enabling an account does not revive revoked sessions")
}

func TestLastAdministratorsAndIdentifierOwnership(t *testing.T) {
	ctx := context.Background()
	catalog, err := Open(filepath.Join(t.TempDir(), "identity.db"))
	require.NoError(t, err)
	defer catalog.Close()
	admin, err := catalog.BootstrapAdmin(ctx, UserInput{Login: "admin", Email: "admin@example.com", Password: "admin-password-233"})
	require.NoError(t, err)
	_, err = catalog.CreateUser(ctx, UserInput{Login: "ADMIN@example.com", Password: "reader-password-233", OrgID: 1, Role: RoleViewer})
	require.ErrorIs(t, err, ErrAccountExists, "email and login aliases must not collide across users")
	users, err := catalog.Users(ctx, 100, 0)
	require.NoError(t, err)
	require.Len(t, users, 1, "failed alias registration is rolled back completely")
	membership, err := catalog.Membership(ctx, 1, admin.ID)
	require.NoError(t, err)
	_, err = catalog.ChangeOrganizationUserRole(ctx, 1, admin.ID, membership.Version, RoleViewer)
	require.ErrorIs(t, err, ErrLastAdministrator)
	_, err = catalog.RemoveOrganizationUser(ctx, 1, admin.ID, membership.Version)
	require.ErrorIs(t, err, ErrLastAdministrator)
	_, err = catalog.SetUserDisabled(ctx, admin.ID, admin.Version, true)
	require.ErrorIs(t, err, ErrLastAdministrator)
	other, err := catalog.CreateUser(ctx, UserInput{Login: "recovery", Password: "recovery-password-233", OrgID: 1, Role: RoleAdmin, IsServerAdmin: true})
	require.NoError(t, err)
	disabled, err := catalog.SetUserDisabled(ctx, admin.ID, admin.Version, true)
	require.NoError(t, err)
	_, err = catalog.SetUserDisabled(ctx, other.ID, other.Version, true)
	require.ErrorIs(t, err, ErrLastAdministrator)
	_, err = catalog.SetUserDisabled(ctx, admin.ID, disabled.Version-1, false)
	require.ErrorIs(t, err, ErrVersionConflict)
	_, err = catalog.SetUserDisabled(ctx, admin.ID, disabled.Version, false)
	require.NoError(t, err)
	_, err = catalog.ChangeOrganizationUserRole(ctx, 1, admin.ID, membership.Version, RoleEditor)
	require.NoError(t, err)
	_, err = catalog.ChangeOrganizationUserRole(ctx, 1, admin.ID, membership.Version, RoleViewer)
	require.ErrorIs(t, err, ErrVersionConflict)
}

func TestSessionsExpireIdleLogoutAndOrganizationDisable(t *testing.T) {
	ctx := context.Background()
	catalog, err := Open(filepath.Join(t.TempDir(), "identity.db"))
	require.NoError(t, err)
	defer catalog.Close()
	user, err := catalog.BootstrapAdmin(ctx, UserInput{Login: "admin", Password: "admin-password-233"})
	require.NoError(t, err)
	org, err := catalog.BeginOrganization(ctx, "Operations")
	require.NoError(t, err)
	org, err = catalog.ActivateOrganization(ctx, org.ID, org.Version)
	require.NoError(t, err)
	_, err = catalog.AddOrganizationUser(ctx, org.ID, user.ID, RoleAdmin)
	require.NoError(t, err)
	_, session, key, err := catalog.Login(ctx, "admin", "admin-password-233", org.ID, time.Hour, time.Minute)
	require.NoError(t, err)
	org, err = catalog.SetOrganizationState(ctx, org.ID, org.Version, OrganizationDisabled)
	require.NoError(t, err)
	_, err = catalog.AuthenticateSession(ctx, key, 1)
	require.ErrorIs(t, err, ErrUnauthenticated, "header selection cannot bypass a disabled cookie context")
	_, err = catalog.SwitchSessionOrganization(ctx, key, 1)
	require.ErrorIs(t, err, ErrUnauthenticated)
	_, err = catalog.SetOrganizationState(ctx, org.ID, org.Version, OrganizationActive)
	require.NoError(t, err)
	require.NoError(t, catalog.db.QueryRow(`UPDATE browser_sessions SET last_seen=? WHERE id=? RETURNING id`, time.Now().Add(-2*time.Minute).UnixMilli(), session.ID).Scan(&session.ID))
	_, err = catalog.AuthenticateSession(ctx, key, 0)
	require.ErrorIs(t, err, ErrUnauthenticated)
	_, session, key, err = catalog.Login(ctx, "admin", "admin-password-233", 1, time.Hour, time.Hour)
	require.NoError(t, err)
	_, err = catalog.db.Exec(`UPDATE browser_sessions SET expires_at=? WHERE id=?`, time.Now().UnixMilli(), session.ID)
	require.NoError(t, err)
	_, err = catalog.AuthenticateSession(ctx, key, 0)
	require.ErrorIs(t, err, ErrUnauthenticated, "expiration at now is not valid")
	_, session, key, err = catalog.Login(ctx, "admin", "admin-password-233", 1, time.Hour, time.Hour)
	require.NoError(t, err)
	require.ErrorIs(t, catalog.RevokeSession(ctx, user.ID+100, session.ID), sql.ErrNoRows)
	_, err = catalog.AuthenticateSession(ctx, key, 0)
	require.NoError(t, err)
	require.NoError(t, catalog.Logout(ctx, key))
	require.NoError(t, catalog.Logout(ctx, key))
	_, err = catalog.AuthenticateSession(ctx, key, 0)
	require.ErrorIs(t, err, ErrUnauthenticated)
}

func TestPasswordHashPolicyAndCancellation(t *testing.T) {
	ctx := context.Background()
	salt, hash, err := makePassword(ctx, "password-233233")
	require.NoError(t, err)
	otherSalt, otherHash, err := makePassword(ctx, "password-233233")
	require.NoError(t, err)
	require.NotEqual(t, salt, otherSalt)
	require.NotEqual(t, hash, otherHash)
	valid, err := verifyPassword(ctx, "password-233233", salt, hash, passwordFormat)
	require.NoError(t, err)
	require.True(t, valid)
	valid, err = verifyPassword(ctx, "password-233233", salt, hash, "untrusted-hash-policy")
	require.NoError(t, err)
	require.False(t, valid)
	cancelled, cancel := context.WithCancel(ctx)
	cancel()
	_, err = passwordKey(cancelled, "password-233233", salt)
	require.ErrorIs(t, err, context.Canceled)
	_, _, err = makePassword(ctx, "short")
	require.Error(t, err)
	_, err = credentialDigest("mp233_session_", sessionCredentialPrefix)
	require.ErrorIs(t, err, ErrUnauthenticated)
}
